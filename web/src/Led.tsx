// LED-Punktraster: 5×7-Matrix pro Ziffer.
const FONT: Record<string, string[]> = {
  "0": ["01110", "10001", "10011", "10101", "11001", "10001", "01110"],
  "1": ["00100", "01100", "00100", "00100", "00100", "00100", "01110"],
  "2": ["01110", "10001", "00001", "00010", "00100", "01000", "11111"],
  "3": ["11110", "00001", "00001", "01110", "00001", "00001", "11110"],
  "4": ["00010", "00110", "01010", "10010", "11111", "00010", "00010"],
  "5": ["11111", "10000", "11110", "00001", "00001", "10001", "01110"],
  "6": ["00110", "01000", "10000", "11110", "10001", "10001", "01110"],
  "7": ["11111", "00001", "00010", "00100", "01000", "01000", "01000"],
  "8": ["01110", "10001", "10001", "01110", "10001", "10001", "01110"],
  "9": ["01110", "10001", "10001", "01111", "00001", "00010", "01100"],
};

export function Led({ value, color = "#fff", label }: { value: number; color?: string; label: string }) {
  const digits = String(Math.min(value, 999)).split("");
  const cols = digits.length * 6 - 1;
  return (
    <svg className="led" viewBox={`0 0 ${cols} 7`} role="img" aria-label={`${label}: ${value}`} style={{ color }}>
      {digits.flatMap((d, i) =>
        FONT[d]!.flatMap((row, y) => [...row].map((c, x) => <circle key={`${i}${x}${y}`} cx={i * 6 + x + 0.5} cy={y + 0.5} r={0.36} fill="currentColor" opacity={c === "1" ? 1 : 0.14} />)),
      )}
    </svg>
  );
}
